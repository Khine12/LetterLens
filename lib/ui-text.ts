/** Just the reader's language (falls back to English). */
export function localLabel(key: LabelKey, language: string): string {
  return LOCAL[language.split(" ")[0]]?.[key] ?? EN[key];
}

/** Reader's language first, then English: "ဘာဆက်လုပ်ရမလဲ · What to do next". */
export function label(key: LabelKey, language: string): string {
  const local = LOCAL[language.split(" ")[0]]?.[key];
  return local ? `${local} · ${EN[key]}` : EN[key];
}
